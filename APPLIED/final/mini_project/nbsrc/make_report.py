def md_table(df, floatfmt=None, max_rows=None, drop=None):
    d = df.drop(columns=drop, errors="ignore") if drop else df
    d = d.head(max_rows) if max_rows else d
    d = d.copy()
    if floatfmt:
        for col, fmt in floatfmt.items():
            if col in d.columns:
                d[col] = d[col].map(lambda x: fmt.format(x) if pd.notna(x) else "-")
    for col in d.columns:
        d[col] = d[col].astype(str).str.replace("|", "/", regex=False)
    header = "| " + " | ".join(str(c) for c in d.columns) + " |"
    sep = "|" + "|".join(["---"] * len(d.columns)) + "|"
    rows = ["| " + " | ".join(str(x) for x in r) + " |" for r in d.itertuples(index=False)]
    return "\n".join([header, sep] + rows)


def figure(filename, caption, note=""):
    """Instruction block telling the writer which image to insert here."""
    global _fig_no
    _fig_no += 1
    lines = [
        "```",
        f"┌─ 🖼  รูปที่ {_fig_no} ─────────────────────────────────────────────",
        f"│  ไฟล์      : outputs/figures/{filename}.png",
        f"│  คำบรรยาย  : รูปที่ {_fig_no} {caption}",
    ]
    if note:
        for i, ln in enumerate(note.split("\n")):
            lines.append(f"│  {'หมายเหตุ  ' if i == 0 else '           '}: {ln}"
                         if i == 0 else f"│              {ln}")
    lines += ["└──────────────────────────────────────────────────────────", "```"]
    return "\n".join(lines)


def table_block(csv_name, title, how="เปิดไฟล์ CSV ด้วย Excel แล้วคัดลอกมาวางใน Word"):
    """Instruction block for a table."""
    global _tbl_no
    _tbl_no += 1
    return "\n".join([
        "```",
        f"┌─ 📊  ตารางที่ {_tbl_no} ────────────────────────────────────────────",
        f"│  ไฟล์      : outputs/tables/{csv_name}.csv",
        f"│  ชื่อตาราง  : ตารางที่ {_tbl_no} {title}",
        f"│  วิธีแทรก   : {how}",
        "└──────────────────────────────────────────────────────────",
        "```",
    ])


def inline_table(title):
    """Caption line for a small table that lives inline — no file to insert, so a
    heavy instruction box would only add noise. Just number it and caption it."""
    global _tbl_no
    _tbl_no += 1
    return f"**ตารางที่ {_tbl_no}** {title}"


